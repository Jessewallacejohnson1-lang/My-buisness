-- A sport's gender and its bare name, so "Girls Swim" (a game) and "Girls Swimming and Diving"
-- (the school's list) meet as girls / swim, and "Dance Team" meets "Dance".
create or replace function private.sport_gender(p text) returns text
language sql immutable set search_path = '' as $$
  select case when g and not b then 'girls' when b and not g then 'boys' end
  from (select lower(p) ~ '\m(girls?|women|womens|women''s)\M' g,
               lower(p) ~ '\m(boys?|men|mens|men''s)\M' b) x
$$;

create or replace function private.sport_base(p text) returns text
language sql immutable set search_path = '' as $$
  select btrim(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
           replace(lower(regexp_replace(p, '\([^)]*\)', '', 'g')), '''s', ''),
           '\m(girls?|boys?|women|men|womens|mens|team|competitive|sju|csb)\M', '', 'g'),
           '\d+\s*-\s*\d+', '', 'g'),
           '\mswimming\M', 'swim', 'g'),
           '\s*(and|&)\s*div(e|ing)\M', '', 'g'),
           '\mtrack\s*(and|&)\s*field\M', 'track', 'g'),
           '[^a-z]+', ' ', 'g'))
$$;

-- Whether a game is this activity's: one of its teams fields the activity, the sports' bare names
-- match, and the genders agree. A game that names no gender ("Volleyball") is the fielding school's
-- default row for that sport: the one naming no gender, else the one whose name starts with the
-- sport ("Volleyball (girls)" over "Boys Volleyball").
create or replace function public.activity_has_event(a public.team_activities, e public.club_events)
returns boolean
language sql stable set search_path = '' as $$
  select e.sport is not null
    and coalesce(a.fielded_by, a.team_id) = any(e.team_ids)
    and private.sport_base(e.sport) = private.sport_base(a.name)
    and case
      when private.sport_gender(e.sport) is not null
        then coalesce(private.sport_gender(a.name), private.sport_gender(e.sport)) = private.sport_gender(e.sport)
      else private.sport_gender(a.name) is not distinct from (
        select private.sport_gender(r.name) from public.team_activities r
        where r.team_id = coalesce(a.fielded_by, a.team_id) and r.fielded_by is null
          and private.sport_base(r.name) = private.sport_base(e.sport)
        order by private.sport_gender(r.name) is not null,
                 lower(r.name) not like private.sport_base(e.sport) || '%', r.sort
        limit 1)
    end
$$;
grant execute on function public.activity_has_event(public.team_activities, public.club_events) to anon, authenticated;

